"""Build eval/REPORT.md from the JSON files in eval/results/.

Usage: python -m eval.report
"""

from __future__ import annotations

import json
from typing import Any

from eval.common import RESULTS
from src.config import ROOT

OUT = ROOT / "eval" / "REPORT.md"


def _load(name: str) -> dict[str, Any] | None:
    p = RESULTS / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def _pct(x: float) -> str:
    return f"{x * 100:.1f}%"


def _meta_line(meta: dict[str, Any]) -> str:
    return (f"LLM `{meta['llm_mode']}` (main `{meta['llm_model_main']}`, fast `{meta['llm_model_fast']}`), "
            f"vectors `{meta['vector_backend']}` (`{meta['embedder']}`), run {meta['timestamp']}")


def leak_section(data: dict[str, Any], title: str, note: str) -> list[str]:
    s = data["summary"]["by_checker"]
    on, off = s["checker_on"], s["checker_off"]
    rows = [
        ("Gated-token leakage", "gated_token"), ("Killer confession / crime detail", "confession"),
        ("Names the real killer", "solution_naming"), ("Accuses someone of the killing", "accusation"),
        ("Innocent's secret given up unprompted", "secret_admission"),
        ("LLM judge: subtle leak", "judge_leak"), ("**Any leak**", "any_leak"),
    ]
    out = [f"### {title}", "", note, "", f"_{_meta_line(data['meta'])}_", "",
           f"{data['meta']['n_prompts']} prompts x {len(data['meta']['suspects'])} suspects = "
           f"{on['n']} turns per condition.", "",
           "| Metric | Checker OFF | Checker ON |", "|---|---:|---:|"]
    out += [f"| {label} | {_pct(off[k])} | {_pct(on[k])} |" for label, k in rows]
    out += [f"| Deflection rate | {_pct(off['deflection_rate'])} | {_pct(on['deflection_rate'])} |",
            f"| Mean regenerations per turn | {off['mean_retries']} | {on['mean_retries']} |", ""]
    cats = data["summary"]["by_category"]
    out += ["Any-leak rate by attack category:", "",
            "| Category | Checker OFF | Checker ON |", "|---|---:|---:|"]
    out += [f"| {c} | {_pct(cats['checker_off'][c])} | {_pct(cats['checker_on'][c])} |"
            for c in cats["checker_on"]]
    sus = data["summary"]["by_suspect"]
    out += ["", "Any-leak rate by suspect:", "", "| Suspect | Checker OFF | Checker ON |",
            "|---|---:|---:|"]
    out += [f"| {k} | {_pct(sus['checker_off'][k])} | {_pct(sus['checker_on'][k])} |"
            for k in sus["checker_on"]]
    return out + [""]


def main() -> None:
    lines = ["# Evaluation report: The Holdout", "",
             "Generated by `make eval` (`python -m eval.report`) from `eval/results/*.json`.", ""]
    leak = _load("leak_tests")
    real = bool(leak and leak["meta"]["llm_mode"] == "real")
    if not real:
        lines += ["> **Offline run.** These numbers come from the deterministic `FakeLLM` and the "
                  "offline hashing embedder, so they validate the pipeline, gating and the checker's "
                  "mechanics, not model behaviour. Re-run `make eval` with `LLM_MODE=real` and "
                  "`VECTOR_BACKEND=pinecone` (keys in `.env`) for real leak rates and retrieval "
                  "quality.", ""]

    lines += ["## 1. Leak tests (checker ON vs OFF)", ""]
    if leak:
        lines += leak_section(leak, "Configured model",
                              "Every prompt runs in a fresh session against each suspect at the start "
                              "of the game (no clues discovered), so almost every case fact is gated.")
    sim = _load("leak_tests_simulated")
    if sim:
        lines += leak_section(
            sim, "Simulated leaky model (mechanism test)",
            "`LeakyFakeLLM` appends its entire system prompt (persona, private brief, retrieved "
            "facts) to every reply: a worst-case model that ignores its rules. This isolates what "
            "the checker itself catches. It catches verbatim dumps via the gate guard (hidden "
            "tokens) and the prompt-scaffold guard; paraphrased leaks of brief-only facts rely on "
            "the LLM review layer, which only the real-model run measures.")

    ret = _load("retrieval_eval")
    lines += ["## 2. Retrieval", ""]
    if ret:
        s = ret["summary"]
        lines += [f"_{_meta_line(ret['meta'])}_", "",
                  f"{ret['meta']['n']} questions with gold chunk ids. Gold chunks are always "
                  "visible to the actor in the question's discovery state. *Gate violations* "
                  "count returned chunks the actor must not see yet.", "",
                  "| Condition | Recall@3 | Recall@5 | Gate violations | Queries with violations |",
                  "|---|---:|---:|---:|---:|"]
        for key, label in (("raw_gated", "No rewrite, gating ON"), ("rewrite_gated", "Rewrite, gating ON"),
                           ("raw_ungated", "No rewrite, gating OFF"), ("rewrite_ungated", "Rewrite, gating OFF")):
            r = s[key]
            lines.append(f"| {label} | {r['recall@3']:.3f} | {r['recall@5']:.3f} | "
                         f"{r['gate_violations']} | {r['queries_with_violations']} |")
        v = s["vague_followups"]
        lines += ["", f"Vague or pronoun-heavy follow-ups ({v['n']} of them): recall@5 "
                  f"{v['raw_recall@5']:.3f} without rewrite vs {v['rewrite_recall@5']:.3f} with rewrite.", ""]
        misses = [r for r in ret["rows"] if r["rewrite_gated"]["r@5"] < 1]
        if misses:
            lines += ["Misses (rewrite, gating ON):", ""]
            lines += [f"- [{r['id']}] `{r['actor']}` \"{r['question']}\" (gold {', '.join(r['gold'])}; "
                      f"got {', '.join(r['rewrite_gated']['top5'])})" for r in misses]
            lines.append("")

    play = _load("playthrough")
    lines += ["## 3. Scripted playthroughs", ""]
    if play:
        o = play["optimal"]
        b = o["verdict"]["breakdown"]
        lines += [f"_{_meta_line(play['meta'])}_", "",
                  f"- **Optimal run:** `{o['verdict']['grade']}`, **{o['verdict']['score']}/100** "
                  f"(suspect {b['suspect']}, alibi {b['alibi']}, eliminations {b['eliminations']}, "
                  f"motive {b['motive']}, turns {b['turns']}) using {o['turns_used']} of 30 turns.",
                  "- **Wrong-suspect runs:** " + "; ".join(
                      f"{w['accused']} -> `{w['first']['grade']}`, then {w['second_accused']} -> "
                      f"`{w['second']['grade']}`" for w in play["wrong"]), "",
                  "Rubric feedback returned for each wrong first accusation:", ""]
        lines += [f"- {w['accused']}: \"{w['first']['feedback']}\"" for w in play["wrong"]]
        lines.append("")

    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
